#!/usr/bin/env bash
# The agent-code-review-setup contract, end to end against a throwaway fleet: a root of
# fake repos, a fake `gh` that answers from fixture files (and applies the real jq filters
# it is handed), and a fake `security` with no keychain items. Nothing here reaches the
# network or the real keychain.
#
# What is asserted is behaviour at the seams, never the scripts' internals
# [LAW:behavior-not-structure]: which directories are the population, what each repo's
# report line says, that a second run is a no-op that says so, that a per-repo failure
# names its cause and fails the pass without stopping it, that the one-repo installer
# converges the same render and refuses a subdirectory, and that review-outcome reads
# only the current head and the newest marker on it.
#
# Run: config/claude/tests/code-review-fleet.sh   (needs git and jq)
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd -P)
skill="$here/../skills/agent-code-review-setup"
fleet="$skill/reconverge-fleet.sh"
install="$skill/install.sh"
outcome="$skill/review-outcome.sh"
probe="$here/../skills/code-review-unblock/probe-accounts.sh"

command -v jq >/dev/null || { echo "FAIL - jq is required" >&2; exit 1; }

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
root="$work/root"; fixtures="$work/gh"; bin="$work/bin"
mkdir -p "$root" "$fixtures" "$bin"
export FAKE_GH="$fixtures"
export PATH="$bin:$PATH"

fail() { echo "FAIL - $*" >&2; exit 1; }
has() { grep -qF -- "$2" <<<"$1" || fail "$3: expected to find '$2' in:"$'\n'"$1"; }
lacks() { ! grep -qF -- "$2" <<<"$1" || fail "$3: expected NOT to find '$2' in:"$'\n'"$1"; }

# --- the fake gh: every answer comes from $FAKE_GH/<owner>__<name>.<kind>; a missing
# fixture is a failed call, which is how a gh outage is staged.
cat >"$bin/gh" <<'SH'
#!/usr/bin/env bash
set -u
key() { printf '%s' "${1//\//__}"; }
flag() { local want="$1"; shift; while [ $# -gt 0 ]; do [ "$1" = "$want" ] && { printf '%s' "$2"; return; }; shift; done; }
case "$1 $2" in
  "auth status") exit 0 ;;
  "repo view")
    url="$(git remote get-url origin)"; n="${url#*github.com}"; n="${n#[:/]}"; printf '%s\n' "${n%.git}" ;;
  "secret list")
    f="$FAKE_GH/$(key "$(flag -R "$@")").secrets.$(flag --app "$@")"
    [ -f "$f" ] || { echo "fake gh: HTTP 403 listing secrets" >&2; exit 1; }
    cat "$f" ;;
  "secret set")   # the value arrives on stdin; what was set lands in <repo>.set.<store>.<name>, byte for byte
    cat >"$FAKE_GH/$(key "$(flag -R "$@")").set.$(flag --app "$@").$3" ;;
  "pr view")
    f="$FAKE_GH/$(key "$(flag -R "$@")").pr.$3.head"
    [ -f "$f" ] || { echo "fake gh: no such PR" >&2; exit 1; }
    cat "$f" ;;
  "api "*)
    path="$2"; repo="${path#repos/}"; repo="${repo%%/actions/*}"; repo="${repo%%/pulls/*}"
    case "$path" in
      */actions/workflows)                f="$FAKE_GH/$(key "$repo").workflows.json" ;;
      */actions/runs?head_sha=*)          f="$FAKE_GH/$(key "$repo").runs.${path##*head_sha=}.json" ;;
      */pulls/*/reviews)                  n="${path##*/pulls/}"; f="$FAKE_GH/$(key "$repo").pr.${n%%/*}.reviews.json" ;;
    esac
    [ -f "$f" ] || { echo "fake gh: HTTP 404 $path" >&2; exit 1; }
    shift 2; filter=""
    while [ $# -gt 0 ]; do
      case "$1" in --paginate) ;; --jq) filter="$2"; shift ;; *) echo "fake gh: unhandled api flag $1" >&2; exit 1 ;; esac; shift
    done
    jq -r "$filter" "$f" ;;
  *) echo "fake gh: unhandled: $*" >&2; exit 1 ;;
esac
SH
# --- the fake keychain: an item is a file $FAKE_KEYCHAIN/<item>. dump-keychain lists them;
# find-generic-password [-a acct] -s <item> [-w] finds one and -w prints its value. With
# FAKE_KEYCHAIN unset no item exists, which is the suite's default.
cat >"$bin/security" <<'SH'
#!/usr/bin/env bash
kc="${FAKE_KEYCHAIN:-/nonexistent}"
case "$1" in
  dump-keychain) for f in "$kc"/*; do [ -f "$f" ] && printf '    "svce"<blob>="%s"\n' "$(basename "$f")"; done; exit 0 ;;
  find-generic-password)
    shift; item=""; print=0
    while [ $# -gt 0 ]; do case "$1" in -a) shift ;; -s) item="$2"; shift ;; -w) print=1 ;; esac; shift; done
    [ -f "$kc/$item" ] || exit 44
    [ "$print" -eq 1 ] && cat "$kc/$item"
    exit 0 ;;
  *) echo "fake security: unhandled: $*" >&2; exit 1 ;;
esac
SH
chmod +x "$bin/gh" "$bin/security"

# --- the fleet on disk
stale='# GENERATED by agent-code-review-setup/install.sh — do not edit by hand.'   # an older generation's header
foreign='# GENERATED by `copirate-review install` from the `comment-review` template.' # another tool's file at the same path
repo() { # name remote-path [workflow content]
  mkdir -p "$root/$1/.github/workflows"
  git -C "$root/$1" init -q -b trunk
  git -C "$root/$1" remote add origin "git@github.com:$2.git"
  git -C "$root/$1" -c user.name=t -c user.email=t@t commit -q --allow-empty -m init
  printf '%s\n' "${3-$stale}" >"$root/$1/.github/workflows/code-review.yml"
}
secrets() { printf 'CLAUDE_CODE_OAUTH_TOKEN\nOTHER\n' >"$fixtures/$1.secrets.$2"; }
workflows() { printf '%s\n' "$2" >"$fixtures/$1.workflows.json"; }
active='{"workflows":[{"path":".github/workflows/code-review.yml","state":"active"}]}'
disabled='{"workflows":[{"path":".github/workflows/code-review.yml","state":"disabled_manually"}]}'
empty='{"workflows":[]}'

repo a o/a;            secrets o__a actions; secrets o__a dependabot; workflows o__a "$active"
repo b o/b;            secrets o__b actions; printf 'OTHER\n' >"$fixtures/o__b.secrets.dependabot"; workflows o__b "$empty"
printf '# leading comment\nEXCLUDE_PATTERNS_EXTRA=foo/**,a#b/**  # a # inside a value is the value; this one is a comment\nMAX_REVIEW_ROUNDS=9\n' >"$root/b/.github/code-review.conf"
repo c o/c;            secrets o__c actions; secrets o__c dependabot; workflows o__c "$active"
printf 'BOGUS=1\n' >"$root/c/.github/code-review.conf"
mkdir -p "$root/d/.github/workflows"; echo stale >"$root/d/.github/workflows/code-review.yml"   # not a repo
mkdir -p "$root/e"; git -C "$root/e" init -q -b trunk                                              # no workflow
repo s promptctl/copirate-code-review-agent; secrets promptctl__copirate-code-review-agent actions
secrets promptctl__copirate-code-review-agent dependabot; workflows promptctl__copirate-code-review-agent "$disabled"
repo w o/w;            secrets o__w actions; secrets o__w dependabot                               # no workflows fixture
repo f o/f "$foreign"; secrets o__f actions; secrets o__f dependabot; workflows o__f "$active"      # another generator's file
repo q o/q;            secrets o__q actions; secrets o__q dependabot; workflows o__q "$active"
printf 'EXCLUDE_PATTERNS_EXTRA=docs/"drafts"/**\n' >"$root/q/.github/code-review.conf"                 # a " would close the YAML scalar it lands in
mkdir -p "$root/n/.github/workflows"; git -C "$root/n" init -q -b trunk; git -C "$root/n" remote add origin git@github.com:o/n.git
printf '%s\n' "$stale" >"$root/n/.github/workflows/code-review.yml"                                # unborn branch: no commit yet
secrets o__n actions; secrets o__n dependabot; workflows o__n "$active"

# --- run 1: first convergence
set +e; out="$("$fleet" "$root" 2>"$work/err")"; rc=$?; set -e
[ "$rc" -eq 1 ] || fail "run 1: expected exit 1 (two repos fail), got $rc"
has "$out" "a                                updated  branch=trunk  workflow=active  secrets=ok" "run 1 a"
has "$out" "b                                updated  branch=trunk  workflow=unregistered  secrets=missing CLAUDE_CODE_OAUTH_TOKEN(dependabot)" "run 1 b"
has "$out" "c                                failed: ERROR: .github/code-review.conf:1: unknown key 'BOGUS'" "run 1 c"
has "$out" "s                                updated  branch=trunk  workflow=disabled_manually  secrets=ok" "run 1 s"
has "$out" "w                                failed: ERROR: could not list workflows on o/w." "run 1 w"
has "$out" "n                                updated  branch=trunk  workflow=active  secrets=ok" "run 1 n: an unborn branch is named, not a git usage line"
has "$out" "q                                failed: ERROR: .github/code-review.conf:1: 'EXCLUDE_PATTERNS_EXTRA' may not contain | & \\ or \"." "run 1 q: a render metacharacter is refused at the conf, naming file:line"
[ "$(cat "$root/q/.github/workflows/code-review.yml")" = "$stale" ] || fail "run 1 q: a refused conf must not render anything"
! grep -qE '^d ' <<<"$out" || fail "run 1: a non-repo directory is not in the population"
! grep -qE '^e ' <<<"$out" || fail "run 1: a repo without the file is not in the population"
! grep -qE '^f ' <<<"$out" || fail "run 1: a repo whose file another tool generated is not in the population"
[ "$(cat "$root/f/.github/workflows/code-review.yml")" = "$foreign" ] || fail "run 1: wrote over another tool's file"
has "$out" "7 repos: 0 unchanged, 4 updated, 3 failed" "run 1 summary"
has "$(cat "$work/err")" "    → .github/code-review.conf adds exclude pattern(s): foo/**" "run 1: render notes sit under their repo"
rendered_b="$(cat "$root/b/.github/workflows/code-review.yml")"
has "$rendered_b" 'EXCLUDE_PATTERNS: ".github/workflows/code-review.yml,dist/**,**/dist/**,build/**,**/build/**,*.lock,package-lock.json,yarn.lock,pnpm-lock.yaml,foo/**,a#b/**"' "b render: conf extra appended to the baseline, # inside a value kept, trailing comment dropped"
has "$rendered_b" 'MAX_REVIEW_ROUNDS: "9"' "b render: conf rounds"
has "$rendered_b" 'uses: promptctl/copirate-code-review-agent@v1' "b render: consumer action ref"
has "$(cat "$root/s/.github/workflows/code-review.yml")" 'uses: ./' "s render: the action's own repo reviews with its PR's code"
has "$(cat "$root/a/.github/workflows/code-review.yml")" 'MAX_REVIEW_ROUNDS: "5"' "a render: fleet default rounds"
lacks "$(cat "$root/a/.github/workflows/code-review.yml")" '__' "a render: no marker left unrendered"
[ "$(cat "$root/d/.github/workflows/code-review.yml")" = stale ] || fail "run 1: wrote into a non-repo directory"
[ "$(cat "$root/w/.github/workflows/code-review.yml")" = "$stale" ] || fail "run 1: a repo whose listing failed must not have been written"
has "$(cat "$work/err")" "    fake gh: HTTP 404 repos/o/w/actions/workflows" "run 1: a failed repo's full stderr sits under its line"
mkdir -p "$work/no-fleet/x"
if "$fleet" "$work/no-fleet" >/dev/null 2>"$work/err"; then fail "an empty population must exit 1"; fi
has "$(cat "$work/err")" "ERROR: no repo under $work/no-fleet carries an installed .github/workflows/code-review.yml" "empty population: names the root"
echo "ok   - run 1: population, per-repo lines, render, failures named, empty root refused, exit 1"

# --- run 2: the two failures fixed, everything else a no-op
rm "$root/c/.github/code-review.conf" "$root/q/.github/code-review.conf"; workflows o__w "$active"
out="$("$fleet" "$root" 2>/dev/null)"
has "$out" "c                                updated  branch=trunk" "run 2 c"
has "$out" "q                                updated  branch=trunk" "run 2 q"
has "$out" "w                                updated  branch=trunk" "run 2 w: the repo that failed last time is written now, and says so"
has "$out" "7 repos: 4 unchanged, 3 updated, 0 failed" "run 2 summary"
echo "ok   - run 2: fixed repos converge, the rest unchanged, exit 0"

# --- run 3: converged fleet is a no-op that says so
out="$("$fleet" "$root" 2>/dev/null)"
has "$out" "7 repos: 7 unchanged, 0 updated, 0 failed" "run 3 summary"
echo "ok   - run 3: re-running a converged fleet reports 0 updated"

# --- the one-repo installer renders the same file and reads the same stores
out="$(cd "$root/a" && "$install" 2>"$work/err")" || fail "install.sh in a: exited $?: $(cat "$work/err")"
has "$out" ".github/workflows/code-review.yml is up to date (uses promptctl/copirate-code-review-agent@v1)" "install a: same render as the fleet"
has "$(cat "$work/err")" "! secret CLAUDE_CODE_OAUTH_TOKEN exists on o/a but keychain item" "install a: no keychain, secret present in both stores -> warn"
mkdir -p "$work/kc"; printf 'tok-1\n' >"$work/kc/CLAUDE_CODE_OAUTH_TOKEN_SIGNUP"
out="$(cd "$root/a" && FAKE_KEYCHAIN="$work/kc" "$install" 2>"$work/err")" || fail "install.sh in a with a keychain item: exited $?: $(cat "$work/err")"
has "$out" "✓ set secret CLAUDE_CODE_OAUTH_TOKEN on o/a (actions dependabot)" "install a + keychain: re-syncs from the item"
for store in actions dependabot; do
  set_file="$fixtures/o__a.set.$store.CLAUDE_CODE_OAUTH_TOKEN"
  [ -f "$set_file" ] || fail "install a + keychain: nothing was set in the $store store"
  [ "$(cat "$set_file")" = "tok-1" ] && [ "$(wc -c <"$set_file")" -eq 5 ] || fail "install a + keychain: $store store got '$(cat "$set_file")', expected the item's value with its newline stripped"
done
: >"$work/kc/CLAUDE_CODE_OAUTH_TOKEN_SIGNUP"
if (cd "$root/a" && FAKE_KEYCHAIN="$work/kc" "$install" >/dev/null 2>"$work/err"); then fail "install.sh with an empty keychain item: expected exit 1"; fi
has "$(cat "$work/err")" "has an empty value — refusing to set an empty CLAUDE_CODE_OAUTH_TOKEN" "install a + empty item: refused before any store is written"
if (cd "$root/b" && "$install" >/dev/null 2>"$work/err"); then fail "install.sh in b: expected exit 1 (dependabot store lacks the secret)"; fi
has "$(cat "$work/err")" "secret CLAUDE_CODE_OAUTH_TOKEN is not set on o/b (dependabot)" "install b: names the store that lacks it"
if (cd "$root/f" && "$install" >/dev/null 2>"$work/err"); then fail "install.sh in f: expected exit 1 (another generator's file)"; fi
has "$(cat "$work/err")" "was generated by another tool (its header names it); not overwriting it." "install f: refuses another generator's file"
[ "$(cat "$root/f/.github/workflows/code-review.yml")" = "$foreign" ] || fail "install f: wrote over another tool's file"
if (cd "$root/a/.github" && "$install" >/dev/null 2>"$work/err"); then fail "install.sh from a subdirectory: expected refusal"; fi
has "$(cat "$work/err")" "not at the root of a git repository" "install from subdirectory: refused"
echo "ok   - install.sh: same render, both stores, root only"

# --- review-outcome reads the current head's newest marker, never an older head's
bot='"user": {"type": "Bot"}'
run() { printf '{"id": %s, "path": ".github/workflows/code-review.yml", "conclusion": "%s", "pull_requests": [{"number": %s}]}' "$1" "$2" "$3"; }   # id conclusion pr
other='{"id": 99, "path": ".github/workflows/ci.yml", "conclusion": "success", "pull_requests": [{"number": 1}]}'   # another workflow's success on the same head is not the reviewer's
runs() { printf '{"workflow_runs": [%s, %s]}\n' "$other" "$2" >"$fixtures/o__a.runs.$1.json"; }
echo HEAD1 >"$fixtures/o__a.pr.1.head"; runs HEAD1 "$(run 1 failure 1)"
cat >"$fixtures/o__a.pr.1.reviews.json" <<JSON
[ {"id": 10, "commit_id": "OLD",   $bot, "body": "round on an old head\n<!-- copirate-code-review-agent -->"},
  {"id": 30, "commit_id": "HEAD1", $bot, "body": "spent, posted nothing <!-- copirate-code-review-agent:unfinished -->"},
  {"id": 20, "commit_id": "HEAD1", $bot, "body": "a round\n<!-- copirate-code-review-agent -->\n"},
  {"id": 50, "commit_id": "HEAD1", $bot, "body": "review of OLD, re-posted without commit_id after a 422; the host stamped HEAD1\n<!-- copirate-code-review-agent -->"} ]
JSON
echo HEAD2 >"$fixtures/o__a.pr.2.head"; runs HEAD2 'null'; printf '[{"id": 1, "commit_id": "OLD", %s, "body": "x <!-- copirate-code-review-agent -->"}]\n' "$bot" >"$fixtures/o__a.pr.2.reviews.json"
echo HEAD3 >"$fixtures/o__a.pr.3.head"; runs HEAD3 "$(run 3 success 3)"; printf '[{"id": 1, "commit_id": "HEAD3", %s, "body": "cap <!-- copirate-code-review-agent:not-reviewed:round-cap -->"}]\n' "$bot" >"$fixtures/o__a.pr.3.reviews.json"
echo HEAD4 >"$fixtures/o__a.pr.4.head"; runs HEAD4 "$(run 4 cancelled 4), $(run 5 success 4)"
printf '[{"id": 1, "commit_id": "HEAD4", %s, "body": "ok\\n<!-- copirate-code-review-agent -->"}, {"id": 2, "commit_id": "HEAD4", "user": {"type": "User"}, "state": "APPROVED"}]\n' "$bot" >"$fixtures/o__a.pr.4.reviews.json"
echo HEAD5 >"$fixtures/o__a.pr.5.head"; runs HEAD5 "$(run 6 failure 5), $(run 8 success 55)"; printf '[{"id": 1, "commit_id": "HEAD5", %s, "body": "stamped by the 422 retry\\n<!-- copirate-code-review-agent -->"}]\n' "$bot" >"$fixtures/o__a.pr.5.reviews.json"
echo HEAD6 >"$fixtures/o__a.pr.6.head"; runs HEAD6 "$(run 7 success 6)"; printf '[{"id": 1, "commit_id": "HEAD6", "user": {"type": "User"}, "body": "pasted\\n<!-- copirate-code-review-agent -->"}]\n' >"$fixtures/o__a.pr.6.reviews.json"
echo HEAD7 >"$fixtures/o__a.pr.7.head"; runs HEAD7 "$(run 11 success 7)"
printf '[{"id": 10, "commit_id": "HEAD7", %s, "body": "round two\\n<!-- copirate-code-review-agent -->"}, {"id": 9, "commit_id": "HEAD7", %s, "body": "cap <!-- copirate-code-review-agent:not-reviewed:round-cap -->"}]\n' "$bot" "$bot" >"$fixtures/o__a.pr.7.reviews.json"
expect() { # pr expected-output expected-rc
  local got rc; set +e; got="$("$outcome" o/a "$1")"; rc=$?; set -e
  [ "$got" = "$2" ] && [ "$rc" -eq "$3" ] || fail "review-outcome PR $1: expected '$2' rc=$3, got '$got' rc=$rc"
}
expect 1 unfinished 1               # newest by id on the current head, not list order, not the old head's round; the mis-stamped retry (no successful run) does not outrank it
expect 2 none 1                     # the only marker belongs to a previous head
expect 3 not-reviewed:round-cap 1
expect 4 reviewed 0                 # a bodiless human approval on the same head is not an artifact
expect 5 none 1                     # a `reviewed` stamp on a head whose run never succeeded is the 422 retry's, not this head's; another PR's success on the same commit does not vouch
expect 6 none 1                     # a marker pasted by a non-Bot account is not the action's
expect 7 reviewed 0                 # two markers survive on one head: the higher id wins, numerically (10 over 9), not by list order
echo "ok   - review-outcome: head-bound, newest-by-id, Bot-only, run-crossed, four outcomes, exit code"

# --- probe-accounts reads the configured account off template.sh's own table
cat >"$bin/claude" <<'SH'
#!/usr/bin/env bash
echo ok
SH
cat >"$bin/timeout" <<'SH'
#!/usr/bin/env bash
shift; exec "$@"
SH
chmod +x "$bin/claude" "$bin/timeout"
printf 'tok-2\n' >"$work/kc/CLAUDE_CODE_OAUTH_TOKEN_SIGNUP"; printf 'tok-3\n' >"$work/kc/CLAUDE_CODE_OAUTH_TOKEN_OTHER"
out="$(FAKE_KEYCHAIN="$work/kc" "$probe" 2>"$work/err")" || fail "probe-accounts: exited $?: $(cat "$work/err")"
has "$out" "configured in template.sh: SIGNUP" "probe: the configured account is the SECRETS table's, read by sourcing it"
has "$out" "* SIGNUP" "probe: the configured account is starred"
has "$out" "  OTHER" "probe: every pool item is probed"
lacks "$out" "(unknown)" "probe: never falls back to an unknown account"
echo "ok   - probe-accounts: configured account read from the table, pool probed"

echo "PASS - agent-code-review-setup"
